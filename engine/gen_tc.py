"""Generate the hardwired-weight block (tc_wrom.v) and the engine top (tc_engine.v)
from a trained ternary model (.npz from train_v2.py or train_14.py).

usage: python3 gen_tc.py model.npz outdir
The fixed RTL (tc_core.v, tc_rsync.v, tc_dsync.v) lives in rtl/ and is copied to outdir.
"""
import sys, os, shutil, numpy as np
from tc_model import clip_model, to_u, TERN_CODE

HERE = os.path.dirname(os.path.abspath(__file__))


def h10(v):
    return f"10'h{to_u(int(v)):03x}"


def gen_wrom(q):
    q = clip_model(q)
    T1, T2, thr, b2 = q['T1'], q['T2'], q['thr'], q['b2']
    NI, H = T1.shape; C = T2.shape[1]
    nz1 = int((T1 != 0).sum()); nz2 = int((T2 != 0).sum())
    L = ["// tc_wrom: hardwired weights, thresholds and biases (GENERATED by gen_tc.py)",
         f"// model: {NI} inputs, {H} hidden, {C} classes; nonzero weights "
         f"{nz1} + {nz2} of {T1.size} + {T2.size}",
         "// Ternary code: 01 = +1, 11 = -1, 00 = 0. Do not edit by hand.",
         "module tc_wrom (",
         "  input      [5:0] i,                // input index",
         "  input      [5:0] j,                // hidden index",
         "  input      [3:0] c,                // class index",
         "  input      [3:0] bc,               // class index for bias",
         "  output reg [1:0] w1,               // layer-1 weight (j,i)",
         "  output reg [1:0] w2,               // layer-2 weight (c,j)",
         "  output reg [29:0] th,              // thresholds of j",
         "  output reg [9:0] bias              // bias of class bc",
         ");", "",
         "  always @* begin", "    case ({j[5:0], i[5:0]})"]
    for jj in range(H):
        for ii in range(NI):
            t = int(T1[ii, jj])
            if t:
                L.append(f"      12'd{(jj << 6) | ii}: w1[1:0] = 2'b{TERN_CODE[t]:02b};")
    L += ["      default: w1[1:0] = 2'b00;", "    endcase", "  end", "",
          "  always @* begin", "    case ({c[3:0], j[5:0]})"]
    for cc in range(C):
        for jj in range(H):
            t = int(T2[jj, cc])
            if t:
                L.append(f"      10'd{(cc << 6) | jj}: w2[1:0] = 2'b{TERN_CODE[t]:02b};")
    L += ["      default: w2[1:0] = 2'b00;", "    endcase", "  end", "",
          "  always @* begin", "    case (j[5:0])"]
    for jj in range(H):
        t = thr[jj]
        L.append(f"      6'd{jj}: th[29:0] = {{{h10(t[0])}, {h10(t[1])}, {h10(t[2])}}};")
    L += ["      default: th[29:0] = 30'b0;", "    endcase", "  end", "",
          "  always @* begin", "    case (bc[3:0])"]
    for cc in range(C):
        if int(b2[cc]):
            L.append(f"      4'd{cc}: bias[9:0] = {h10(b2[cc])};")
    L += ["      default: bias[9:0] = 10'b0;", "    endcase", "  end", "", "endmodule", ""]
    return "\n".join(L), (NI, H, C)


def gen_top(NI, H, C):
    return f"""// tc_engine: v2 ternary engine block (GENERATED by gen_tc.py)
// Hardwired model: {NI} inputs, {H} hidden, {C} classes.
module tc_engine (
  input        clk,                  // engine clock (from ESP32)
  input        rst_n,                // async active-low reset pin
  input        cs_n,                 // chip select, active low
  input        mode,                 // 0 = hardwired, 1 = streamed
  input  [7:0] din,                  // byte bus
  output       busy,                 // run in progress
  output [3:0] result,               // argmax class
  output [9:0] score,                // last class score
  output       score_tgl             // toggles on each score update
);

  wire       nrst;
  wire       mode_s;
  wire [5:0] idx_i;
  wire [5:0] idx_j;
  wire [3:0] idx_c;
  wire [3:0] idx_bc;
  wire [1:0] hw_w1;
  wire [1:0] hw_w2;
  wire [29:0] hw_th;
  wire [9:0] hw_bias;

  tc_rsync u_rsync (
    .clk      (clk),
    .nrst_in  (rst_n),
    .nrst_out (nrst)
  );

  tc_dsync u_mode (
    .clk  (clk),
    .nrst (nrst),
    .din  (mode),
    .dout (mode_s)
  );

  tc_wrom u_wrom (
    .i    (idx_i),
    .j    (idx_j),
    .c    (idx_c),
    .bc   (idx_bc),
    .w1   (hw_w1),
    .w2   (hw_w2),
    .th   (hw_th),
    .bias (hw_bias)
  );

  tc_core #(
    .NI_LAST (6'd{NI - 1}),
    .H_LAST  (6'd{H - 1}),
    .C_LAST  (4'd{C - 1})
  ) u_core (
    .clk       (clk),
    .rst_n     (nrst),
    .cs_n      (cs_n),
    .mode_s    (mode_s),
    .din       (din),
    .hw_w1     (hw_w1),
    .hw_w2     (hw_w2),
    .hw_th     (hw_th),
    .hw_bias   (hw_bias),
    .idx_i     (idx_i),
    .idx_j     (idx_j),
    .idx_c     (idx_c),
    .idx_bc    (idx_bc),
    .busy      (busy),
    .result    (result),
    .score     (score),
    .score_tgl (score_tgl)
  );

endmodule
"""


def build(q, outdir):
    os.makedirs(outdir, exist_ok=True)
    wrom, (NI, H, C) = gen_wrom(q)
    open(os.path.join(outdir, 'tc_wrom.v'), 'w').write(wrom)
    open(os.path.join(outdir, 'tc_engine.v'), 'w').write(gen_top(NI, H, C))
    for f in ('tc_core.v', 'tc_rsync.v', 'tc_dsync.v'):
        shutil.copy(os.path.join(HERE, 'rtl', f), outdir)
    return NI, H, C


if __name__ == '__main__':
    q = dict(np.load(sys.argv[1]))
    print(build(q, sys.argv[2]))
